export function gearDescription(name) {
  const item=name.replace(/^\d+ /,'');
  if(item.endsWith('(trinket)')) return 'A personal keepsake. Use it to show something about your character or their past.';
  if(item.endsWith('gaming set')) return 'Tools for playing this game. Proficiency lets you add your Proficiency Bonus to relevant checks.';
  if(/^Arrows?$|^Bolts?$/.test(item)) return 'Ammunition for a compatible weapon.';
  const key=Object.keys(gearIntro).find(key=>item===key||item===key+'s'||item.startsWith(key+' ('));
  return gearIntro[key]??null;
}
